"""System theme target: Alacritty.

Renders alacritty.toml, the terminal's font size and colours, into the theme
state directory. The vendor fragment (desktop/defaults/alacritty.toml,
imported from ~/.config/alacritty/alacritty.toml) imports its fallback
(alacritty-colors.toml, the default dark render) and then this file. Alacritty
loads imports in order and the importing file last, so the fragment itself
sets neither colours nor size.

Alacritty watches every file it imported and reloads on a change, so there is
nothing to signal.
"""
import json

import theme_terminal

NAME = 'alacritty'

HEADER = (
    '# Generated by theme-apply.py (scripts/theme_alacritty.py) from the shell\'s\n'
    '# appearance tokens. Rewritten whenever the appearance changes: put colour\n'
    '# or font size overrides in ~/.config/alacritty/alacritty.toml instead.\n'
)
ANSI_NAMES = ('black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white')


def render(tokens):
    colors = theme_terminal.colors(tokens)
    value = json.dumps
    lines = [
        '[font]', f'size = {theme_terminal.font_size(tokens)}', '',
        '[colors.primary]', f'foreground = {value(colors["foreground"])}', f'background = {value(colors["background"])}', '',
        '[colors.selection]', f'text = {value(colors["selection_foreground"])}',
        f'background = {value(colors["selection_background"])}', '',
        '[colors.cursor]', f'text = {value(colors["cursor_text"])}', f'cursor = {value(colors["cursor"])}', '',
        '[colors.hints.start]', f'foreground = {value(colors["cursor_text"])}', f'background = {value(colors["url"])}', '',
    ]
    for group, offset in (('normal', 0), ('bright', 8)):
        lines.append(f'[colors.{group}]')
        lines.extend(f'{name} = {value(colors["ansi"][offset + index])}' for index, name in enumerate(ANSI_NAMES))
        lines.append('')
    return {'alacritty.toml': HEADER + '\n'.join(lines)}


