"""System theme target: Ghostty.

Renders ghostty.conf, the terminal's font size and colours, into the theme
state directory. ~/.config/ghostty/config (seeded by personal-init) loads the
vendor fragment (desktop/defaults/ghostty.conf, which carries the default dark
theme as a fallback), then this file, then the person's own personal.conf:
Ghostty reads `config-file`s in order, so these values win over the fallback
and personal ones win over these.

Ghostty's GTK application reloads its configuration on SIGUSR2 (its
application.zig installs the handler), so running windows follow at once.
"""
import os
import subprocess

import theme_terminal

NAME = 'ghostty'

HEADER = (
    '# Generated by theme-apply.py (scripts/theme_ghostty.py) from the shell\'s\n'
    '# appearance tokens. Rewritten whenever the appearance changes: put colour\n'
    '# or font-size overrides in ~/.config/ghostty/personal.conf instead.\n'
)
# Ghostty's GUI processes, matched on the whole command line: `ghostty` or the
# Nix wrapper's `.ghostty-wrapped`, by any path, without a `+action` CLI
# subcommand (those exit at once and keep SIGUSR2's default: terminate).
GUI_PATTERN = r'([^ ]*/)?\.?ghostty(-wrapped)?( [^+].*)?'
RELOAD_TIMEOUT = 5


def settings(tokens):
    """(key, value) pairs in file order."""
    colors = theme_terminal.colors(tokens)
    pairs = [
        ('font-size', theme_terminal.font_size(tokens)),
        ('foreground', colors['foreground']),
        ('background', colors['background']),
        ('selection-foreground', colors['selection_foreground']),
        ('selection-background', colors['selection_background']),
        ('cursor-color', colors['cursor']),
        ('cursor-text', colors['cursor_text']),
    ]
    pairs.extend(('palette', f'{index}={value}') for index, value in enumerate(colors['ansi']))
    return pairs


def render(tokens):
    return {'ghostty.conf': HEADER + ''.join(f'{key} = {value}\n' for key, value in settings(tokens))}


def reload(tokens, directory):
    try:
        result = subprocess.run(
            ['pkill', '--signal', 'USR2', '--uid', str(os.getuid()), '--full', '--exact', GUI_PATTERN],
            stdin=subprocess.DEVNULL, capture_output=True, text=True, timeout=RELOAD_TIMEOUT)
    except FileNotFoundError:
        # A bare environment (the driver tests), not a desktop; new windows
        # read the file regardless.
        return
    except subprocess.TimeoutExpired:
        raise RuntimeError('pkill did not finish') from None
    # 1 means no Ghostty is running: nothing to reload.
    if result.returncode not in (0, 1):
        detail = result.stderr.strip().splitlines()
        raise RuntimeError(f'pkill failed with status {result.returncode}'
                           + (f': {detail[-1]}' if detail else ''))
