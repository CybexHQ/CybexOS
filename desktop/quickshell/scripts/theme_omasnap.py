"""System theme target: Omasnap, the screenshot overlay.

Renders omasnap/colors.toml into the theme state directory. Omasnap reads
Omarchy's colors.toml keys for its toolbar, tooltips, previews and selection
outline; the Cybex OS package points it at this directory
(nix/packages/omasnap.nix). It derives its buttons, borders and tooltips from
these few colours, and draws the selection outline in the accent. The
screenshot itself and the colours of annotations are never themed.

Omasnap watches the file and restyles its open windows when it changes, so
there is nothing to signal.
"""
import json

NAME = 'omasnap'
FILE = 'omasnap/colors.toml'

HEADER = (
    '# Generated by theme-apply.py (scripts/theme_omasnap.py) from the shell\'s\n'
    '# appearance tokens. Rewritten whenever the appearance changes.\n'
)


def render(tokens):
    colors = tokens['colors']
    value = json.dumps
    lines = [
        f'background = {value(colors["background"])}',
        f'foreground = {value(colors["text"])}',
        f'light_foreground = {value(colors["textMuted"])}',
        f'accent = {value(colors["accent"])}',
        f'orange = {value(colors["amber"])}',
        '',
        # The toolbar and previews rest on the shell's panel colour.
        '[popups]',
        f'background = {value(colors["surface"])}',
        f'text = {value(colors["text"])}',
        '',
    ]
    return {FILE: HEADER + '\n'.join(lines)}


